import os
import time
from datetime import datetime, timedelta

import psycopg
from psycopg.rows import dict_row
from flask import Flask, flash, g, jsonify, redirect, render_template, request, url_for
from prometheus_client import Counter, Gauge, Histogram, generate_latest, CONTENT_TYPE_LATEST

APP_NAME = "ChargePoint — EV Charging Portal"
DATABASE_URL = os.environ.get("DATABASE_URL", "")
app = Flask(__name__)
app.secret_key = os.environ.get("FLASK_SECRET_KEY") or os.environ.get("SECRET_KEY") or "change-this-secret-key-before-production"

HTTP_REQUESTS = Counter("ev_portal_http_requests_total", "HTTP requests", ["method", "endpoint", "status"])
HTTP_LATENCY = Histogram("ev_portal_http_request_duration_seconds", "HTTP request latency", ["endpoint"])
AVAILABILITY_SEARCHES = Counter("ev_portal_availability_searches_total", "Availability searches")
BOOKING_ATTEMPTS = Counter("ev_portal_booking_attempts_total", "Reservation attempts", ["result"])
QUEUE_JOINS = Counter("ev_portal_queue_joins_total", "Queue join attempts", ["result"])
FAULT_REPORTS = Counter("ev_portal_fault_reports_total", "Fault reports submitted")
ACTIVE_RESERVATIONS = Gauge("ev_portal_active_reservations", "Active demo reservations")
WAITING_QUEUE = Gauge("ev_portal_waiting_queue", "Customers currently waiting in demo queues")
AVAILABLE_CHARGERS = Gauge("ev_portal_available_chargers", "Chargers currently available")

SCHEMA_STATEMENTS = [
    """CREATE TABLE IF NOT EXISTS stations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        address TEXT NOT NULL,
        area TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS chargers (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        station_id INTEGER NOT NULL REFERENCES stations(id),
        code TEXT NOT NULL,
        power_kw INTEGER NOT NULL,
        connector TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'available'
    )""",
    """CREATE TABLE IF NOT EXISTS reservations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        charger_id INTEGER NOT NULL REFERENCES chargers(id),
        customer_name TEXT NOT NULL,
        vehicle TEXT NOT NULL,
        slot_start TEXT NOT NULL,
        slot_end TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'confirmed',
        created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS queue_entries (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        station_id INTEGER NOT NULL REFERENCES stations(id),
        customer_name TEXT NOT NULL,
        vehicle TEXT NOT NULL,
        created_at TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'waiting'
    )""",
    """CREATE TABLE IF NOT EXISTS fault_reports (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        charger_id INTEGER NOT NULL REFERENCES chargers(id),
        customer_name TEXT NOT NULL,
        issue TEXT NOT NULL,
        details TEXT,
        created_at TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'open'
    )""",
]


def get_db():
    if "db" not in g:
        if not DATABASE_URL:
            raise RuntimeError("DATABASE_URL is not set. Configure the PostgreSQL RDS connection.")
        g.db = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
    return g.db


@app.teardown_appcontext
def close_db(_error=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


