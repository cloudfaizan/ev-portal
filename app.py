@app.before_request
def start_timer():
    g.request_started = time.perf_counter()


@app.after_request
def collect_metrics(response):
    endpoint = request.endpoint or "unknown"
    HTTP_REQUESTS.labels(request.method, endpoint, str(response.status_code)).inc()
    elapsed = time.perf_counter() - getattr(g, "request_started", time.perf_counter())
    HTTP_LATENCY.labels(endpoint).observe(elapsed)
    return response


def refresh_gauges():
    db = get_db()
    AVAILABLE_CHARGERS.set(db.execute("SELECT COUNT(*) AS count FROM chargers WHERE status='available'").fetchone()["count"])
    ACTIVE_RESERVATIONS.set(db.execute("SELECT COUNT(*) AS count FROM reservations WHERE status='confirmed'").fetchone()["count"])
    WAITING_QUEUE.set(db.execute("SELECT COUNT(*) AS count FROM queue_entries WHERE status='waiting'").fetchone()["count"])


@app.route("/")
def index():
    init_db()
    db = get_db()
    search = request.args.get("q", "").strip()
    if search:
        AVAILABILITY_SEARCHES.inc()
        stations = db.execute(
            """SELECT s.*, COUNT(CASE WHEN c.status='available' THEN 1 END) AS available_count,
                      COUNT(c.id) AS total_count
               FROM stations s LEFT JOIN chargers c ON c.station_id=s.id
               WHERE s.name LIKE %s OR s.area LIKE %s OR s.address LIKE %s
               GROUP BY s.id ORDER BY s.name""",
            (f"%{search}%", f"%{search}%", f"%{search}%"),
        ).fetchall()
    else:
        stations = db.execute(
            """SELECT s.*, COUNT(CASE WHEN c.status='available' THEN 1 END) AS available_count,
                      COUNT(c.id) AS total_count
               FROM stations s LEFT JOIN chargers c ON c.station_id=s.id
               GROUP BY s.id ORDER BY s.name"""
        ).fetchall()
    chargers = db.execute(
        """SELECT c.*, s.name AS station_name, s.area
           FROM chargers c JOIN stations s ON s.id=c.station_id ORDER BY s.name, c.code"""
    ).fetchall()
    reservations = db.execute(
        """SELECT r.*, c.code, s.name AS station_name
           FROM reservations r JOIN chargers c ON c.id=r.charger_id
           JOIN stations s ON s.id=c.station_id
           ORDER BY r.id DESC LIMIT 8"""
    ).fetchall()
    queue_entries = db.execute(
        """SELECT q.*, s.name AS station_name
           FROM queue_entries q JOIN stations s ON s.id=q.station_id
           WHERE q.status='waiting' ORDER BY q.id DESC LIMIT 8"""
    ).fetchall()
    refresh_gauges()
    return render_template("index.html", app_name=APP_NAME, stations=stations, chargers=chargers,
                           reservations=reservations, queue_entries=queue_entries, search=search)


@app.post("/reserve")
def reserve():
    init_db()
    name = request.form.get("customer_name", "").strip()
    vehicle = request.form.get("vehicle", "").strip()
    charger_id = request.form.get("charger_id", "").strip()
    slot_start = request.form.get("slot_start", "").strip()
    if not name or not vehicle or not charger_id or not slot_start:
        flash("Please complete every reservation field.", "error")
        return redirect(url_for("index"))
    try:
        start_dt = datetime.fromisoformat(slot_start)
        if start_dt < datetime.now():
            raise ValueError()
        end_dt = start_dt + timedelta(minutes=30)
    except ValueError:
        flash("Choose a valid future time slot.", "error")
        return redirect(url_for("index"))
    db = get_db()
    try:
        # Lock this charger row so simultaneous requests cannot book it at the same time.
        db.execute("SELECT id FROM chargers WHERE id=%s FOR UPDATE", (charger_id,))
        charger = db.execute("SELECT * FROM chargers WHERE id=%s", (charger_id,)).fetchone()
        if charger is None or charger["status"] != "available":
            db.rollback()
            BOOKING_ATTEMPTS.labels("unavailable").inc()
            flash("That charger is not available. Please choose another charger or join the queue.", "error")
            return redirect(url_for("index"))
        overlap = db.execute(
            """SELECT COUNT(*) AS count FROM reservations WHERE charger_id=%s AND status='confirmed'
               AND slot_start < %s AND slot_end > %s""",
            (charger_id, end_dt.isoformat(timespec="minutes"), start_dt.isoformat(timespec="minutes")),
        ).fetchone()["count"]
        if overlap:
            db.rollback()
            BOOKING_ATTEMPTS.labels("slot_conflict").inc()
            flash("That charger already has a reservation overlapping this slot. Try another charger/time.", "error")
            return redirect(url_for("index"))
        booking = db.execute(
            """INSERT INTO reservations(charger_id,customer_name,vehicle,slot_start,slot_end,created_at)
               VALUES (%s,%s,%s,%s,%s,%s) RETURNING id""",
            (charger_id, name, vehicle, start_dt.isoformat(timespec="minutes"),
             end_dt.isoformat(timespec="minutes"), datetime.now().isoformat(timespec="seconds")),
        ).fetchone()
        db.commit()
        BOOKING_ATTEMPTS.labels("success").inc()
        flash(f"Reservation confirmed for {name}. Demo booking reference: EV-{booking['id']:05d}", "success")
    except psycopg.Error:
        db.rollback()
        BOOKING_ATTEMPTS.labels("database_error").inc()
        flash("The reservation could not be saved. Please try again.", "error")
    refresh_gauges()
    return redirect(url_for("index"))


@app.post("/queue")
def join_queue():
    init_db()
    name = request.form.get("customer_name", "").strip()
    vehicle = request.form.get("vehicle", "").strip()
    station_id = request.form.get("station_id", "").strip()
    if not name or not vehicle or not station_id:
        flash("Enter your name, vehicle, and station to join the queue.", "error")
        return redirect(url_for("index"))
    db = get_db()
    station = db.execute("SELECT id FROM stations WHERE id=%s", (station_id,)).fetchone()
    if not station:
        flash("Please choose a valid station.", "error")
        return redirect(url_for("index"))
    db.execute("INSERT INTO queue_entries(station_id,customer_name,vehicle,created_at) VALUES (%s,%s,%s,%s)",
               (station_id, name, vehicle, datetime.now().isoformat(timespec="seconds")))
    db.commit()
    QUEUE_JOINS.labels("success").inc()
    refresh_gauges()
    flash(f"You have joined the waiting queue at the selected station, {name}.", "success")
    return redirect(url_for("index"))


@app.post("/fault")
def report_fault():
    init_db()
    charger_id = request.form.get("charger_id", "").strip()
    name = request.form.get("customer_name", "").strip()
    issue = request.form.get("issue", "").strip()
    details = request.form.get("details", "").strip()
    if not charger_id or not name or not issue:
        flash("Enter your name, charger, and issue type.", "error")
        return redirect(url_for("index"))
    db = get_db()
    charger = db.execute("SELECT id FROM chargers WHERE id=%s", (charger_id,)).fetchone()
    if not charger:
        flash("Please choose a valid charger.", "error")
        return redirect(url_for("index"))
    db.execute("INSERT INTO fault_reports(charger_id,customer_name,issue,details,created_at) VALUES (%s,%s,%s,%s,%s)",
               (charger_id, name, issue, details[:1000], datetime.now().isoformat(timespec="seconds")))
    db.execute("UPDATE chargers SET status='faulty' WHERE id=%s", (charger_id,))
    db.commit()
    FAULT_REPORTS.inc()
    refresh_gauges()
    flash("Fault report submitted. The charger is now marked faulty in this demo.", "success")
    return redirect(url_for("index"))


