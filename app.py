@app.get("/api/stations")
def api_stations():
    init_db()
    db = get_db()
    rows = db.execute(
        """SELECT s.id,s.name,s.address,s.area,
                  COUNT(CASE WHEN c.status='available' THEN 1 END) AS available,
                  COUNT(c.id) AS total
           FROM stations s LEFT JOIN chargers c ON c.station_id=s.id GROUP BY s.id ORDER BY s.name"""
    ).fetchall()
    AVAILABILITY_SEARCHES.inc()
    return jsonify([dict(row) for row in rows])


